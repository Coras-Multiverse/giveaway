/**
 * Converts any country input (e.g. "PK 🇵🇰", "PK", "pakistan", "US") into a full country name with flag.
 */
export function getFullCountryName(rawCountry) {
  if (!rawCountry || rawCountry === "Unknown" || rawCountry === "N/A") {
    return "Unknown";
  }

  const str = String(rawCountry).trim();

  // If it's a 2-letter code like "PK" or "US"
  const upper = str.toUpperCase();
  if (COUNTRY_MAP[upper]) {
    return COUNTRY_MAP[upper];
  }

  // If it starts with a 2-letter code followed by space/emoji like "PK 🇵🇰" or "DO 🇩🇴"
  const prefixMatch = str.match(/^([A-Za-z]{2})\s+/);
  if (prefixMatch && COUNTRY_MAP[prefixMatch[1].toUpperCase()]) {
    return COUNTRY_MAP[prefixMatch[1].toUpperCase()];
  }

  // If it's already a full name like "India 🇮🇳", return as is or ensure proper flag
  return str;
}
